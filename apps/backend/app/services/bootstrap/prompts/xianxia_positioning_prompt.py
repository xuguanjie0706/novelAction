"""修仙直白线 Step 0 立项 prompt（修仙第一性原理，非番茄打脸框架）。

与番茄 algo_positioning 的本质区别：番茄锁「当众打脸贵族」式核心爽感，引擎是打脸；
修仙直白文的引擎是**数值爬升本身**——核心爽感是碾压同阶/越阶斩杀/夺天材地宝，
张力来自瓶颈/天劫/寿元/资源稀缺。本 prompt 从修仙读者口味推导定位，不套打脸地图。
"""
from __future__ import annotations

# 修仙直白文主流子类型（供模型选择，避免边缘玩法）
_XIANXIA_SUBGENRES = (
    "升级流（数值爬升为主引擎）/ 宗门流（宗门内崛起争锋）/ "
    "散修崛起（草根逆袭无背景）/ 争霸流（势力/天下争雄）/ 洪荒封神（神话体系）"
)


def build_xianxia_positioning_prompt(logline: str, premise: str) -> str:
    """返回修仙立项 user prompt。"""
    return f"""一句话创意：{logline}
作者补充：{(premise or '')[:400] or '（无）'}

你在做一部【番茄·玄幻修仙直白文】的立项会议。修仙直白文的爽感引擎不是「打脸」，
而是**数值爬升本身**：突破瓶颈、碾压同阶、扮猪吃虎、越阶斩杀、夺天材地宝、闯秘境。
请从修仙读者口味推导定位，返回 JSON：

{{
  "subgenre": "从下列选最契合的一个，照抄：{_XIANXIA_SUBGENRES}",
  "core_satisfaction": "ONE 核心爽感，必须是修仙画面感(15字内)，如『越阶一剑斩杀宗门天才』，禁止写『爽』『打脸』这类空词",
  "progression_fantasy": "升级幻想主线一句话：主角从什么起点(废材/散修/低境)走到什么终局(掌控天地/飞升/证道)",
  "tension_source": "张力主来源(从 瓶颈/天劫/寿元/宿敌追杀/资源稀缺 选1主+1次)，说明为何主角不能轻松变强",
  "opening_fortune": "开局机缘类型(传承/神秘老者/系统/重生/废体觉醒/吞噬天赋 等)，30字内，必须是第1章就能给出的",
  "power_fantasy_curve": "数值爽感节奏：约每几章一次『小突破/碾压』、每几章一次『大境突破/越阶大爽点』",
  "reader_tags": ["番茄修仙站内真实标签 3-5 个，如：升级、宗门、夺宝、扮猪吃虎、无敌流"],
  "completion_hook": "开局第1章留人钩子(修仙语义，50字内：身份落差+变强预告+悬念)",
  "taboo_check": "是否触碰违禁(是/否)，若是指出"
}}

判断标准：
1. core_satisfaction 必须能让读者『脑内播放一段修仙画面』，且是数值/境界层面的爽，不是社交打脸。
2. tension_source 必须解释清楚『为什么主角变强有阻力』——没有阻力就没有爽点反差。
3. opening_fortune 必须是开局第1章可兑现的，不接受『后期渐入佳境』。
4. 只返回 JSON，不要任何解释文字。"""
