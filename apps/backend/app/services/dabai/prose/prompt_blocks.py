def build_continuity_system_rules(*, has_prewarn: bool, has_scene: bool) -> str:
    """合并 continuity 变体为单函数。"""
    base_tail = (
        "   已发生的事不可推翻——金手指若已绑定禁止再写绑定流程；"
        "主角若已逆袭禁止写回废人/经脉尽断；\n"
        "   五拍须按【五拍执行】落法，不可把剧情时间线倒回上一章之前；\n"
    )
    if has_prewarn:
        head = (
            "7. 衔接硬约束：开头必须按【写前导演单】的「开头写法」执行，"
            "正面承接上一章正文实际结尾；\n"
            "   导演单给出「衔接交代」时必须先写位移/转场，没给则紧接上章末句同一瞬间续写，"
            "禁止自行另起场景；\n"
        )
    else:
        head = (
            "7. 衔接硬约束：若非第1章，开头必须正面承接【上章结尾】末句场景；\n"
        )
    word_rule = (
        "8. 五拍各用紧凑篇幅，禁止重复铺陈同一桥段；严禁超过目标字数上限；"
        "章末钩子事件只演一次，禁止末段复读章纲 end_hook 原句。"
    )
    if has_scene:
        word_rule = _WORD_RULES_SCENE
    return head + base_tail + word_rule + "\n"
