"""钩子类型库 + 目标情绪调色板（章纲一等公民）。

设计动机（2026-06-16，借鉴 story-long-write 的「情绪先于故事 + 命名钩子库」）：
  - 大白文每章必须能一句话说清「交付什么情绪」，说不清的章不该存在 → target_emotion。
  - 章尾钩子是追读命门，自由生成易坍缩成同一招 → 给命名钩子库 + 相邻轮换闸门。
本模块是钩子/情绪的唯一事实源，被 prompts_chapter（注入）与 linter（校验）共用。
"""

from __future__ import annotations

# 章尾 13 式（追读引擎，end_hook 的类型；hook_type 字段取此枚举键）──────────────
HOOK_END_TYPES: dict[str, str] = {
    "强敌登场": "更强对手/靠山现身，威胁升级",
    "打脸预告": "爽点延迟，明确预告下章当众打脸/兑现",
    "身份揭露": "秘密/真相抛出一角，读者要追下文求证",
    "危机降临": "主角骤陷险境/被算计，命悬一线",
    "反转钩": "局势在章末骤变，颠覆本章结论",
    "悬念问题": "抛出一个让人想答的谜题",
    "蓄势待发": "实力/底牌已备，下章即爆，吊读者胃口",
    "机缘出现": "宝物/机遇/贵人在章末浮现，待取",
    "误会升级": "矛盾被推到临界，冲突一触即发",
    "倒计时": "设定限时/期限压力，逼读者追进度",
    "关系突变": "敌友转换/感情线突进，关系格局变了",
    "选择困境": "章末抛出两难抉择，读者替主角揪心",
    "信息炸弹": "一句话颠覆既有认知，余震留到下章",
}

# 章首 7 式（开篇抓人，可选标注 open_hook_type，不强制）──────────────────────────
HOOK_OPEN_TYPES: dict[str, str] = {
    "冲突式": "开篇直接进对峙/冲突，不铺垫",
    "悬念式": "首段抛未解问题/异常",
    "反差式": "身份或处境的强反差入场",
    "危机式": "开场即险境/倒计时",
    "台词式": "一句挑衅/宣言/狠话入场",
    "信息差式": "读者已知而角色未知，制造张力",
    "承接式": "直接顺上一章末钩起笔",
}

# 目标情绪调色板（target_emotion 建议词，不限定但优先取此）────────────────────────
EMOTION_PALETTE: tuple[str, ...] = (
    "爽感释放", "扬眉吐气", "震撼", "痛快", "解气", "期待感", "热血", "紧张",
    "好奇", "意难平", "甜", "虐心", "憋屈蓄势", "反转惊愕", "扮猪吃虎的窃喜",
)


def hook_library_block() -> str:
    """注入章纲 prompt 的钩子库 + 情绪要求块。"""
    ends = "、".join(HOOK_END_TYPES.keys())
    emos = "、".join(EMOTION_PALETTE)
    return (
        "\n【目标情绪 + 钩子类型库（硬约束）】\n"
        "  ★情绪先于故事★：每章先想清『本章交付什么情绪』，填 target_emotion"
        f"（优先取：{emos}；说不清交付什么情绪的章不该存在）。\n"
        f"  ★章尾钩子类型★：end_hook 必须能归入下列 13 式之一，填 hook_type：{ends}。\n"
        "  ★钩子轮换★：相邻两章 hook_type 不得相同；全卷 13 式尽量铺开，"
        "禁止整卷只用『强敌登场/打脸预告』两招循环。\n"
        "  ★情绪起伏★：整卷 target_emotion 要有张弛（憋屈蓄势↔爽感释放↔甜/虐交替），"
        "禁止全程同一种情绪一条直线。\n"
    )


def normalize_hook_type(val: object) -> str:
    """把模型给的 hook_type 归一到库内键（模糊包含匹配），无法匹配则原样保留。"""
    s = str(val or "").strip()
    if not s or s in HOOK_END_TYPES:
        return s
    for key in HOOK_END_TYPES:
        if key in s or s in key:
            return key
    return s


def is_known_hook_type(val: object) -> bool:
    return str(val or "").strip() in HOOK_END_TYPES
